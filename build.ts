// Build dist/agent-shell.js from src/: one bundled file that runs with Bun, plus its
// SHA-256 in dist/agent-shell.js.sha256. Bundling only — no compile step, Bun runs it.
// Run: bun run build

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const dist = path.join(import.meta.dir, "dist");
const outfile = path.join(dist, "agent-shell.js");
const result = await Bun.build({
  entrypoints: [path.join(import.meta.dir, "src", "main.ts")],
  target: "bun",
  format: "esm",
  minify: false,
});
if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}
const banner =
  "#!/usr/bin/env bun\n" +
  "// agent-shell, bundled from src/ by build.ts. Do not edit this file.\n";
const code = banner + (await result.outputs[0]!.text()).replace(/^#!.*\n/, "");
fs.mkdirSync(dist, { recursive: true });
fs.writeFileSync(outfile, code);
fs.chmodSync(outfile, 0o755);
const sum = createHash("sha256").update(code).digest("hex");
fs.writeFileSync(outfile + ".sha256", `${sum}  agent-shell.js\n`);
console.log(`Built ${outfile} (${fs.statSync(outfile).size} bytes, sha256 ${sum})`);
